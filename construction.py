"""Generate the coordinate recipe in Matt Holden, A 1104-cap in dimension nine.

Coordinates are (t, z1, z2, z3, z4, v1, v2, v3, v4), modulo 3.
This implements the fiber table and the equations defining B_+, M, B_-, K.
Only the Python standard library is needed.
"""

import argparse
import csv
import io
from itertools import product
from pathlib import Path

ROOT = Path(__file__).resolve().parent
HEADER = ('t', 'z1', 'z2', 'z3', 'z4', 'v1', 'v2', 'v3', 'v4')


def signings(*supports):
    """All nonzero signings of the given one-based supports in four coordinates."""
    points = set()
    for support in supports:
        for signs in product((1, 2), repeat=len(support)):
            v = [0] * 4
            for i, a in zip(support, signs):
                v[i - 1] = a
            points.add(tuple(v))
    return points


def parity_class(epsilon):
    return {v for v in product((1, 2), repeat=4)
            if (v[0] * v[1] * v[2] * v[3]) % 3 == epsilon}


def fibers():
    """The plus and minus columns of the manuscript's five-row fiber table."""
    p1, p2 = parity_class(1), parity_class(2)
    axes12, axes34 = signings((1,), (2,)), signings((3,), (4,))
    plus = [signings((1, 2, 3), (1, 2, 4)),
            signings((1, 3), (2, 4), (3, 4)),
            signings((1, 4), (2, 3), (3, 4)),
            axes12 | p1, axes12 | p2]
    minus = [signings((1, 3, 4), (2, 3, 4)),
             signings((1, 2), (1, 4), (2, 3)),
             signings((1, 2), (1, 3), (2, 4)),
             axes34 | p1, axes34 | p2]
    return plus, minus


def construct():
    axes = signings((1,), (2,), (3,), (4,))
    carriers = [axes] + [signings(tuple(j for j in range(1, 5) if j != i))
                         for i in range(1, 5)]
    plus, minus = fibers()
    points = set()
    for t, local_fibers in ((1, plus), (2, minus)):
        for addresses, local in zip(carriers, local_fibers):
            points.update((t,) + z + v for z in addresses for v in local)
    # M = E x E union (F1 union F2) x {0}.
    points.update((0,) + z + v for z in axes for v in axes)
    points.update((0,) + z + (0, 0, 0, 0) for z in carriers[1] | carriers[2])
    return sorted(points)


def csv_text(points):
    buffer = io.StringIO(newline='')
    writer = csv.writer(buffer, lineterminator='\n')
    writer.writerow(HEADER)
    writer.writerows(points)
    return buffer.getvalue()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, default=ROOT / 'data/cap1104.csv')
    parser.add_argument('--check', action='store_true',
                        help='Compare generated bytes with the saved CSV; write nothing.')
    args = parser.parse_args()
    points = construct()
    payload = csv_text(points).encode('ascii')
    if args.check:
        if args.output.read_bytes() != payload:
            parser.exit(1, 'FAIL: saved CSV differs from the coordinate recipe.\n')
        print('PASS: saved CSV exactly matches the coordinate recipe (1104 points).')
    else:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_bytes(payload)
        print(f'Wrote {len(points)} points to {args.output}.')


if __name__ == '__main__':
    main()
